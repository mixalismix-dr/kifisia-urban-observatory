export function translate(value) {
  if (language() === 'en' || !value) return value;
  const match = /^(\s*)([\s\S]*?)(\s*)$/.exec(value);
  const phrase = match[2];
  let result = el[phrase];
  if (result === undefined) {
    for (const [pattern, render] of patterns) {
      const parts = pattern.exec(phrase);
      if (parts) { result = render(parts); break; }
    }
  }
  return `${match[1]}${result ?? phrase}${match[3]}`;
}

const remembered = new WeakMap();
const rememberedAttrs = new WeakMap();
const attrs = ['aria-label', 'placeholder', 'alt', 'title', 'content'];

function renderText(node) {
  const previous = remembered.get(node);
  const original = previous?.rendered === node.nodeValue ? previous.original : node.nodeValue;
  const rendered = translate(original);
  remembered.set(node, { original, rendered });
  if (node.nodeValue !== rendered) node.nodeValue = rendered;
}

function renderElement(element) {
  const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) renderText(walker.currentNode);
  for (const node of [element, ...element.querySelectorAll('*')]) {
    let records = rememberedAttrs.get(node);
    if (!records) { records = new Map(); rememberedAttrs.set(node, records); }
    for (const attr of attrs) {
      const value = node.getAttribute?.(attr);
      if (!value) continue;
      const previous = records.get(attr);
      const original = previous?.rendered === value ? previous.original : value;
      const rendered = translate(original);
      records.set(attr, { original, rendered });
      if (rendered !== value) node.setAttribute(attr, rendered);
    }
  }
}

export function initI18n() {
  const switcher = document.querySelector('#language-select');
  switcher.value = language();
  const render = () => {
    document.documentElement.lang = language();
    renderElement(document.body);
    renderElement(document.head);
  };
  switcher.addEventListener('change', () => {
    localStorage.setItem('kifisia-language', switcher.value);
    render();
  });
  render();
  new MutationObserver((changes) => {
    for (const change of changes) {
      if (change.type === 'characterData') renderText(change.target);
      if (change.type === 'attributes') renderElement(change.target);
      for (const node of change.addedNodes) {
        if (node.nodeType === Node.TEXT_NODE) renderText(node);
        if (node.nodeType === Node.ELEMENT_NODE) renderElement(node);
      }
    }
  }).observe(document.body, { subtree: true, childList: true, characterData: true,
    attributes: true, attributeFilter: attrs });
}
